# Generate cross-validated random vectors for the Wishbone B4 testbench.
#
# Each vector encodes:
#   kind  1=write_single  2=read_single
#         3=write_burst   4=read_burst
#         5=write_oor     6=read_oor      (always result in ERR)
#   addr  byte address (DATA_WIDTH/8 aligned for in-range vectors)
#   data  write payload (writes only)
#   sel   byte-select mask
#   burst number of beats (1 for single, 2..MAX for burst)
#   exp_resp 0=ACK  1=ERR  2=RTY
#   exp_rdata expected RDATA on the LAST beat of a read (single or burst)
#
# A Python software shadow of the slave register file maintains the
# exact storage state so the C++ harness can compare.

import random
import sys

NUM = 1024
NUM_REGS = 16
DATA_WIDTH = 32
BYTES = DATA_WIDTH // 8
ADDR_BITS = 32

random.seed(0xB4ABCDEF)

shadow = [0] * NUM_REGS

print("// SPDX-License-Identifier: GPL-3.0-or-later OR LicenseRef-Commercial")
print("// AUTO-GENERATED by tb/gen_random_vectors.py.")
print("// Do not edit by hand; regenerate with `make regen_vectors`.")
print("#pragma once")
print("#include <cstdint>")
print("#include <cstddef>")
print()
print("struct WbVec {")
print("    uint8_t  kind;")
print("    uint32_t addr;")
print("    uint32_t data;")
print("    uint8_t  sel;")
print("    uint8_t  burst;")
print("    uint8_t  exp_resp;   // 0=ACK 1=ERR 2=RTY")
print("    uint32_t exp_rdata;  // last beat for reads")
print("};")
print()
print("static const WbVec kWbVectors[] = {")


def apply_sel(old: int, new: int, sel: int) -> int:
    out = old
    for b in range(BYTES):
        if (sel >> b) & 1:
            mask = 0xFF << (b * 8)
            out = (out & ~mask) | (new & mask)
    return out & 0xFFFFFFFF


count = 0
for _ in range(NUM):
    kind_pick = random.random()
    if kind_pick < 0.04:
        # Out-of-range write
        kind = 5
        addr = random.randint(NUM_REGS * BYTES, (NUM_REGS * BYTES) * 4) & 0xFFFFFFFC
        data = random.getrandbits(32)
        sel = random.randint(0, 15)
        exp_resp = 1
        exp_rdata = 0
        burst = 1
    elif kind_pick < 0.08:
        # Out-of-range read
        kind = 6
        addr = random.randint(NUM_REGS * BYTES, (NUM_REGS * BYTES) * 4) & 0xFFFFFFFC
        data = 0
        sel = 0
        exp_resp = 1
        exp_rdata = 0
        burst = 1
    elif kind_pick < 0.18:
        # Write burst (avoid index 0..2 just to keep deterministic
        # interaction simple; bursts increment from base addr).
        burst = random.choice([2, 4, 8])
        max_start = NUM_REGS - burst
        if max_start < 1:
            burst = 2
            max_start = NUM_REGS - 2
        idx = random.randint(0, max_start)
        addr = idx * BYTES
        data = random.getrandbits(32)
        sel = 0xF
        # Apply across the burst (master replicates wdata across beats).
        for b in range(burst):
            shadow[idx + b] = apply_sel(shadow[idx + b], data, sel)
        kind = 3
        exp_resp = 0
        exp_rdata = 0
    elif kind_pick < 0.28:
        # Read burst
        burst = random.choice([2, 4, 8])
        max_start = NUM_REGS - burst
        if max_start < 1:
            burst = 2
            max_start = NUM_REGS - 2
        idx = random.randint(0, max_start)
        addr = idx * BYTES
        data = 0
        sel = 0
        kind = 4
        exp_resp = 0
        exp_rdata = shadow[idx + burst - 1]   # value of LAST beat
    elif kind_pick < 0.64:
        # Single write
        idx = random.randint(0, NUM_REGS - 1)
        addr = idx * BYTES
        data = random.getrandbits(32)
        sel = random.randint(1, 15)
        shadow[idx] = apply_sel(shadow[idx], data, sel)
        kind = 1
        burst = 1
        exp_resp = 0
        exp_rdata = 0
    else:
        # Single read
        idx = random.randint(0, NUM_REGS - 1)
        addr = idx * BYTES
        data = 0
        sel = 0
        kind = 2
        burst = 1
        exp_resp = 0
        exp_rdata = shadow[idx]

    print(f"    {{ {kind}u, 0x{addr:08x}u, 0x{data:08x}u, "
          f"0x{sel:x}u, {burst}u, {exp_resp}u, 0x{exp_rdata:08x}u }},")
    count += 1

print("};")
print()
print(f"static const std::size_t kWbVectorCount = {count};")
